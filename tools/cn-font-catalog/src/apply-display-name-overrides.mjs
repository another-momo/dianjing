/**
 * 一次性 displayName 覆盖（零网络）：读现役 cn-catalog.ts → 解析 →
 * 按 display-name-overrides.json 为缺 displayName 的条目补中文显示名 → 同款模板重写。
 *
 * 背景：build.mjs 的 displayName 采收自 dist 子族目录名（四条规则），拼音/英文 family
 * 的包往往没有 CJK 目录名可采，picker 里裸拼音不可读。覆盖表来源 = 2026-09-26 调研
 * （@chinese-fonts/index 主真源 + 上游 README / md2card 交叉佐证），只收佐证收敛项。
 *
 * 规则：只补缺不覆盖（已有 displayName 的条目跳过并报告）；覆盖表键必须全部命中
 * 现役族，未命中即报错退出（防死键/防拼写漂移）。别名不单独处理——查询先解析到
 * 合并条目。与 prune-catalog-packages.mjs 共用解析与重写模板，重跑幂等。
 *
 * 运行：bun tools/cn-font-catalog/src/apply-display-name-overrides.mjs
 * 验收闸：写盘后 git diff 只许新增 displayName 行——出现任何其他 churn 即停汇报。
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { formatArray, formatEntry, formatRecord } from './merge.mjs'

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const CATALOG_TS = join(REPO_ROOT, 'packages', 'core', 'src', 'text', 'font', 'cn-catalog.ts')
const OVERRIDES_JSON = join(dirname(fileURLToPath(import.meta.url)), 'display-name-overrides.json')

const { overrides } = JSON.parse(readFileSync(OVERRIDES_JSON, 'utf8'))
const overrideMap = new Map(Object.entries(overrides))
if (overrideMap.size === 0) {
  console.error('display-name-overrides.json 的 overrides 为空')
  process.exit(1)
}

function parseCatalogTs(source) {
  const startToken = 'export const CN_FONT_CATALOG: CnFontCatalogEntry[] = '
  const start = source.indexOf(startToken)
  if (start === -1) throw new Error('找不到 CN_FONT_CATALOG 起点')
  const eqIdx = source.indexOf('= ', start) + 2
  const arrStart = source.indexOf('[', eqIdx)
  if (arrStart === -1) throw new Error('找不到数组起点 [')
  let depth = 0
  let inString = false
  let stringChar = ''
  let escape = false
  for (let i = arrStart; i < source.length; i++) {
    const c = source[i]
    if (escape) {
      escape = false
      continue
    }
    if (inString) {
      if (c === '\\') escape = true
      else if (c === stringChar) inString = false
      continue
    }
    if (c === "'" || c === '"') {
      inString = true
      stringChar = c
      continue
    }
    if (c === '[') depth++
    else if (c === ']') {
      depth--
      if (depth === 0) {
        const arrText = source.slice(arrStart, i + 1)
        // 输入是生成物（非用户输入），Function 构造器解析 JS 字面量安全可控。
        return new Function(`return (${arrText});`)()
      }
    }
  }
  throw new Error('找不到匹配的 ]')
}

function parseAliasTs(source) {
  const startToken = 'export const LEGACY_CN_FAMILY_ALIAS: Record<string, string> = '
  const start = source.indexOf(startToken)
  if (start === -1) throw new Error('找不到 LEGACY_CN_FAMILY_ALIAS 起点')
  const objStart = source.indexOf('{', start + startToken.length)
  const objEnd = source.indexOf('\n}', objStart)
  if (objStart === -1 || objEnd === -1) throw new Error('找不到别名表边界')
  const aliases = new Map()
  for (const m of source
    .slice(objStart, objEnd)
    .matchAll(/'((?:\\.|[^'\\])*)': '((?:\\.|[^'\\])*)'/g)) {
    aliases.set(m[1], m[2])
  }
  return aliases
}

const source = readFileSync(CATALOG_TS, 'utf8')
const entries = parseCatalogTs(source)
const beforeAliases = parseAliasTs(source)

const knownFamilies = new Set(entries.map((entry) => entry.family))
const deadKeys = [...overrideMap.keys()].filter((family) => !knownFamilies.has(family))
if (deadKeys.length > 0) {
  console.error(`覆盖表键未命中现役族（${deadKeys.length}）：`)
  for (const key of deadKeys) console.error(`  ✗ ${key}`)
  process.exit(1)
}

const applied = []
const skipped = []
for (const entry of entries) {
  const displayName = overrideMap.get(entry.family)
  if (displayName === undefined) continue
  if (entry.displayName) {
    skipped.push(`${entry.family}（已有 '${entry.displayName}'）`)
    continue
  }
  entry.displayName = displayName
  applied.push(`${entry.family} → ${displayName}`)
}

const aliasEntries = [...beforeAliases.entries()].sort((a, b) => a[0].localeCompare(b[0]))
const today = new Date().toISOString().slice(0, 10)
const ts = `/**
 * GENERATED by tools/cn-font-catalog/src/build.mjs — 请勿手改，重跑管线更新。
 * 构建日期：${today} | 目录规模：合并后 ${entries.length} 族收录 / ${aliasEntries.length} 条字重拆族别名
 *
 * T42 S1：中文网字计划全量目录（registry 精选之外的 @chinese-fonts/* 包）。
 * catalog 族白名单语义 = 默认停用（opt-in，D-c）；授权以包内 license 原文为准，未审计（D-d）。
 *
 * 字重聚合：同包内、族名仅差一个词表字重后缀（空格/连字符分隔；词表 =
 * extralight/ultralight/semibold/demibold/extrabold/ultrabold/thin/light/regular
 * /normal/medium/bold/black/heavy，长词优先匹配）者并为一组，base = 去后缀名。
 * 旧族名以 LEGACY_CN_FAMILY_ALIAS 兜底（picker 持久化恢复兼容），两函数查询
 * 自动跳别名指向合并条目。
 */

export interface CnFontCatalogEntry {
  family: string
  /** 中文显示名（采自 dist 子族目录名，四条全满足才填：①dir 恰解 1 family；②该 family 在本包仅来自此 dir；③dir 含 CJK；④dir ≠ family）。展示用，family 身份不变 */
  displayName?: string
  package: string
  /** 构建时实解版本（钉扎可重现 + piece 缓存键稳定，D-g） */
  version: string
  /** npm 包内 license 字段原文（未审计，展示用） */
  license: string
  variable: boolean
  /** result.css 实见字重（静态档集合；VF 为区间端点） */
  weights: number[]
  /** CDN base 覆盖（缺省 = jsdelivr）；运行时透传 descriptor.baseURL。2026-09-06 复测 jsdelivr 已支持非 ASCII 路径（37/37 族全绿），全量目录零回退 */
  base?: string
}

export const CN_FONT_CATALOG: CnFontCatalogEntry[] = ${formatArray(entries, formatEntry)}

export const LEGACY_CN_FAMILY_ALIAS: Record<string, string> = ${formatRecord(
  aliasEntries,
  ([from, to]) => `  '${escapeSingleQuotedImpl(from)}': '${escapeSingleQuotedImpl(to)}'`
)}

const catalogByFamily = new Map(CN_FONT_CATALOG.map((entry) => [entry.family, entry]))

export function cnCatalogEntry(family: string): CnFontCatalogEntry | undefined {
  const direct = catalogByFamily.get(family)
  if (direct) return direct
  const aliased = LEGACY_CN_FAMILY_ALIAS[family]
  return aliased ? catalogByFamily.get(aliased) : undefined
}

export function isCnCatalogFamily(family: string): boolean {
  if (catalogByFamily.has(family)) return true
  const aliased = LEGACY_CN_FAMILY_ALIAS[family]
  return aliased ? catalogByFamily.has(aliased) : false
}
`

function escapeSingleQuotedImpl(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

writeFileSync(CATALOG_TS, ts)
console.log(
  `[apply-display-name-overrides] 补 ${applied.length} 条；跳过已有 ${skipped.length} 条；族 ${entries.length} / 别名 ${aliasEntries.length} 不变`
)
for (const line of applied) console.log(`  + ${line}`)
for (const line of skipped) console.log(`  = ${line}`)
